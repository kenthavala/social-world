"""Report factuality: counted numbers must be derivable; LLM prose must stay separate.

The counted report is generated by rule from stored rows. This test does not trust
the renderer: it collects every numeric token in the markdown and checks that each
one can be produced from the run's own data (stored analytics/report/quality JSON,
database counts, configuration, manifest, dates) or from a documented ratio of two
such counts. A fabricated number has no source and fails the test.

The optional executive summary is generated by a model. It must never be mixed into
the counted text: it lives in its own stored field and every export labels it.
"""
