def _collect(obj, out: set[float]) -> None:
    if isinstance(obj, dict):
        for v in obj.values():
            _collect(v, out)
    elif isinstance(obj, (list, tuple)):
        for v in obj:
            _collect(v, out)
    elif isinstance(obj, bool):
        return
    elif isinstance(obj, (int, float)):
        out.add(float(obj))
    elif isinstance(obj, str):
        for m in re.finditer(r"\d+(?:\.\d+)?", obj):
            out.add(float(m.group()))


def _derivable_numbers(run_id: str) -> set[float]:
    """Every number the report is allowed to state, plus documented ratios of counts."""
    numbers: set[float] = set()
    row = db.query_one("SELECT * FROM runs WHERE id=?", (run_id,))
    rep = db.query_one("SELECT * FROM reports WHERE run_id=?", (run_id,))
    source = db.query_one("SELECT * FROM sources WHERE id=?", (row["source_id"],))
    for blob in (row["config_json"], row["scenario_json"], row["provider_json"],
                 row["manifest_json"], row["created_at"], row["started_at"],
                 row["finished_at"], row["seed"], row["current_tick"],
                 row["last_completed_tick"], row["llm_calls_used"],
                 source["brief_json"] if source else None,
                 source["pages"] if source else None,
                 rep["analytics_json"] if rep else None,
                 rep["report_json"] if rep else None,
                 rep["created_at"] if rep else None):
        try:
            _collect(db.uj(blob) if isinstance(blob, str) else blob, numbers)
        except Exception:
            _collect(blob, numbers)

    _collect(compute_realism(run_id), numbers)
    _collect(build_findings(run_id), numbers)
    _collect(build_narrative(run_id), numbers)

    counts = {
        "agents": db.scalar("SELECT COUNT(*) FROM agents WHERE run_id=?", (run_id,)) or 0,
        "posts": db.scalar("SELECT COUNT(*) FROM posts WHERE run_id=?", (run_id,)) or 0,
        "system_posts": db.scalar(
            "SELECT COUNT(*) FROM posts WHERE run_id=? AND kind='system'", (run_id,)) or 0,
        "fallback_posts": db.scalar(
            "SELECT COUNT(*) FROM posts WHERE run_id=? AND is_fallback=1", (run_id,)) or 0,
        "sourced_posts": db.scalar(
            "SELECT COUNT(*) FROM posts WHERE run_id=? AND cited_chunk_ids_json"
            " NOT IN ('[]','')", (run_id,)) or 0,
        "edges": db.scalar("SELECT COUNT(*) FROM edges WHERE run_id=?", (run_id,)) or 0,
        "follows": db.scalar(
            "SELECT COUNT(*) FROM edges WHERE run_id=? AND follows=1", (run_id,)) or 0,
        "memories": db.scalar("SELECT COUNT(*) FROM memories WHERE run_id=?", (run_id,)) or 0,
        "stance_rows": db.scalar(
            "SELECT COUNT(*) FROM stance_history WHERE run_id=?", (run_id,)) or 0,
        "events": db.scalar("SELECT COUNT(*) FROM events WHERE run_id=?", (run_id,)) or 0,
        "calls": db.scalar("SELECT COUNT(*) FROM llm_calls WHERE run_id=?", (run_id,)) or 0,
        "reactions": db.scalar("SELECT COUNT(*) FROM reactions WHERE run_id=?", (run_id,)) or 0,
        "chunks": db.scalar("SELECT COUNT(*) FROM chunks WHERE source_id=?",
                            (row["source_id"],)) or 0,
        "issues": len(db.uj(db.scalar(
            "SELECT brief_json FROM sources WHERE id=?", (row["source_id"],)), {}).get("issues") or []),
        "groups": len(db.uj(db.scalar(
            "SELECT brief_json FROM sources WHERE id=?", (row["source_id"],)), {}).get(
                "stakeholder_groups") or []),
        "rounds": row["last_completed_tick"] or 0,
        "tick_target": (db.uj(row["config_json"], {}) or {}).get("ticks") or 0,
        "writes_per_tick": (db.uj(row["config_json"], {}) or {}).get("writes_per_tick") or 0,
        "chunk_pages": db.scalar(
            "SELECT COALESCE(SUM(page_end),0) FROM chunks WHERE source_id=?",
            (row["source_id"],)) or 0,
    }
    _collect(counts, numbers)

    # Rounding variants: the renderer formats stored values at 0-4 decimals.
    expanded = set(numbers)
    for x in list(numbers):
        for k in range(0, 5):
            expanded.add(round(x, k))
    return expanded


def test_every_number_in_the_counted_report_is_derivable(client, finished_run):
    run_id = finished_run
    md = client.get(f"/api/runs/{run_id}/report").json()["report_md"]
    assert md
    allowed = _derivable_numbers(run_id)
    missing: list[tuple[str, str]] = []
    for line in md.splitlines():
        for m in NUM_RE.finditer(line):
            raw = m.group(1).replace(",", "")
            value = float(raw)
            if not any(abs(value - a) < 1e-6 for a in allowed):
                missing.append((m.group(0), line.strip()[:160]))
    assert not missing, "numbers with no source in the run data:\n" + "\n".join(
        f"  {n!r} in: {line}" for n, line in missing[:25])


def test_llm_summary_is_stored_and_exported_separately(client, finished_run):
    run_id = finished_run
    # Stand in for the model: store exactly what generate_essay_report stores.
    sentence = "Opinion on the congestion charge stayed mixed across the recorded rounds."
    sections = {"executive_summary": sentence, "limitations": "Generated prose only."}
    db.execute("UPDATE reports SET essay_json=?, essay_meta_json=? WHERE run_id=?",
               (db.j(sections), db.j({"provider": "mock", "model": "mock-1",
                                      "from_cache": False, "created_at": "2026-10-24T00:00:00",
                                      "report_created_at": "2026-10-24T00:00:00"}), run_id))

    counted = client.get(f"/api/runs/{run_id}/report").json()
    assert sentence not in counted["report_md"]  # counted text is not model text
    assert "No AI wrote it" in counted["report_md"]
    assert counted["essay"]["sections"]["executive_summary"] == sentence

    exported_md = client.get(f"/api/runs/{run_id}/export?format=md").text
    assert sentence in exported_md
    assert "LLM draft" in exported_md and "generated, not counted data" in exported_md
    # The label precedes the generated sentence.
    assert exported_md.index("LLM draft") < exported_md.index(sentence)

    exported_json = client.get(f"/api/runs/{run_id}/export?format=json").json()
    assert exported_json["report"]["essay"]["honesty"] == (
        "LLM draft; generated prose; not counted data")
    assert exported_json["report"]["essay"]["sections"]["executive_summary"] == sentence
    # The counted snapshot is a separate object with its own provenance label.
    assert exported_json["report"]["origin"].startswith("Counted report")


# ---------------------------------------------------------------------------
# Independent recomputation: the prominent numbers must match SQL, not just
# "appear somewhere in the stored analytics".
# ---------------------------------------------------------------------------

def _table(md: str, header: str) -> list[list[str]]:
    lines = md.splitlines()
    start = lines.index(header) + 2
    rows = []
    for line in lines[start:]:
        if not line.startswith("|"):
            break
        rows.append([c.strip() for c in line.strip().strip("|").split("|")])
    return rows


def _num(text: str) -> float:
    return float(text.replace("+", "").replace(",", "").replace("%", "").strip())


def test_headline_numbers_match_independent_recomputation(client, finished_run):
    run_id = finished_run
    md = client.get(f"/api/runs/{run_id}/report").json()["report_md"]
    run = db.query_one("SELECT * FROM runs WHERE id=?", (run_id,))
    brief = db.uj(db.scalar("SELECT brief_json FROM sources WHERE id=?",
                            (run["source_id"],)), {}) or {}
    issues = {i["name"]: i["id"] for i in brief.get("issues") or []}
    last_tick = run["last_completed_tick"]

    n_agents = db.scalar("SELECT COUNT(*) FROM agents WHERE run_id=?", (run_id,))
    n_posts = db.scalar("SELECT COUNT(*) FROM posts WHERE run_id=?", (run_id,))
    n_edges = db.scalar("SELECT COUNT(*) FROM edges WHERE run_id=?", (run_id,))

    # 1. Executive summary: the five headline counts.
    m = re.search(
        r"\*\*(\d+) modelled agents\*\* into \*\*(\d+) stakeholder groups\*\* and let them "
        r"discuss \*\*(\d+) issues\*\* for \*\*(\d+) rounds\*\*, producing \*\*(\d+) posts\*\*",
        md)
    assert m, "executive summary scale sentence not found"
    assert int(m.group(1)) == n_agents
    assert int(m.group(2)) == len(brief.get("stakeholder_groups") or [])
    assert int(m.group(3)) == len(brief.get("issues") or [])
    assert int(m.group(4)) == last_tick
    assert int(m.group(5)) == n_posts

    # 2. Scale row in the header table.
    scale = next(row for row in _table(md, "|  |  |") if row[0] == "**Scale**")[1]
    assert f"{n_agents} agents" in scale
    assert f"{last_tick} rounds" in scale
    assert f"{n_posts} posts" in scale

    # 3. Issue landscape: start, end, change, buckets and spread, from stance_history.
    def stances_at(tick: int) -> dict[tuple[str, str], float]:
        return {(r["agent_id"], r["issue_id"]): float(r["value"]) for r in db.query(
            "SELECT agent_id, issue_id, value FROM stance_history WHERE run_id=? AND tick=?",
            (run_id, tick))}

    first, last = stances_at(1), stances_at(last_tick)
    assert len(last) == n_agents * len(issues)
    for name, iid in issues.items():
        row = next(r for r in _table(
            md, "| Issue | Start | End | Change | Support | Undecided | Oppose | Spread |")
            if r[0] == name)
        finals = [v for (aid, i), v in last.items() if i == iid]
        starts = [v for (aid, i), v in first.items() if i == iid]
        # `statistics.mean`, not sum/len: the renderer's `_mean` is
        # `round(statistics.mean(vals), 3)` and statistics.mean sums floats
        # exactly (Fraction arithmetic), so sum/len can differ in the last bits
        # and cross a 3-dp rounding boundary.
        start_mean = round(mean(starts), 3)
        end_mean = round(mean(finals), 3)
        # The renderer formats these at 2 dp; compare the formatted value exactly.
        assert row[1] == f"{start_mean:+.2f}"
        assert row[2] == f"{end_mean:+.2f}"
        assert row[3] == f"{round(end_mean - start_mean, 3):+.2f}"
        assert int(row[4]) == sum(1 for v in finals if v >= 0.15)
        assert int(row[5]) == sum(1 for v in finals if -0.15 < v < 0.15)
        assert int(row[6]) == sum(1 for v in finals if v <= -0.15)
        assert _num(row[7]) == pytest.approx(max(finals) - min(finals), abs=0.0006)

    # 4. Stakeholder landscape: agent counts and group means, from stance_history joined
    #    to the agents table (not from the stored analytics snapshot).
    group_of = {r["id"]: r["stakeholder_group"] for r in db.query(
        "SELECT id, stakeholder_group FROM agents WHERE run_id=?", (run_id,))}
    for row in _table(md, "| Group | Agents | Start | End | Change | Network role | Priority issues |"):
        name = row[0]
        members = {aid for aid, g in group_of.items() if g == name}
        assert int(row[1]) == len(members)
        # Reproduce the renderer's own definition: the group start/end are the means
        # over every member's stance on every issue, and its change is the mean of the
        # paired per-agent changes - NOT the difference of the two rounded means. The
        # two are equal in exact arithmetic but differ by up to 0.001 after rounding,
        # which flipped a displayed "+0.00"/"-0.00" and made this test fail once in
        # four full-suite runs. Both are asserted: the renderer's value exactly, and
        # that the two definitions agree within the rounding they are printed at.
        g_first: list[float] = []
        g_last: list[float] = []
        g_deltas: list[float] = []
        for iid in issues.values():
            iv = [first.get((aid, iid)) for aid in members]
            fv = [last.get((aid, iid)) for aid in members]
            iv = [v for v in iv if v is not None]
            fv = [v for v in fv if v is not None]
            if not fv:
                continue
            g_first.extend(iv)
            g_last.extend(fv)
            g_deltas.extend([f - i for i, f in zip(iv, fv)])
        g_start = round(mean(g_first), 3)
        g_end = round(mean(g_last), 3)
        g_change = round(mean(g_deltas), 3)
        assert row[2] == f"{g_start:+.2f}"
        assert row[3] == f"{g_end:+.2f}"
        assert row[4] == f"{g_change:+.2f}"
        assert abs(g_change - (g_end - g_start)) <= 0.002, (
            "the printed change disagrees with the printed start/end")

    # 5. Network finding: edges, agents and the per-agent ratio.
    m = re.search(r"(\d+) directed relationships connect (\d+) agents — about "
                  r"([\d.]+) per agent", md)
    assert m, "network finding not found"
    assert int(m.group(1)) == n_edges
    assert int(m.group(2)) == n_agents
    assert float(m.group(3)) == pytest.approx(n_edges / n_agents, abs=0.051)

    # 6. Citation coverage, where the report claims every post cited the source.
    sourced = db.scalar(
        "SELECT COUNT(*) FROM posts WHERE run_id=? AND cited_chunk_ids_json NOT IN ('[]','')",
        (run_id,))
    if "every one of which cited the source document" in md:
        assert sourced == n_posts
    m = re.search(r"(\d+) of (\d+) posts \((\d+)%\) cited at least one passage", md)
    assert m
    assert int(m.group(1)) == sourced
    assert int(m.group(2)) == n_posts
    assert int(m.group(3)) == round(100 * sourced / n_posts)

