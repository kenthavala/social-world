# A numeric token, with its sign. The lookbehind stops the parser reading the tail of
# a date (2026-10-24), an id (run_b67) or a version (3.11.9) as a number.
NUM_RE = re.compile(r"(?<![\w.])(-?\d+(?:[.,]\d+)?)(%?)")


